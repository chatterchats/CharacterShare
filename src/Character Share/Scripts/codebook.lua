-- ---------------------------------------------------------------------------
-- Frozen ZC1 manifest and invariant check
--
-- These fingerprints intentionally cover all compact-id-bearing state. If any
-- value below changes, existing ZC1 codes could decode to different assets.
-- Fail module load immediately rather than silently shipping an incompatible
-- ZC1 dictionary.
-- ---------------------------------------------------------------------------

M.FROZEN_MANIFEST = {
    revision = 1,
    tagCount = 121,
    tagHash = 0x12FC8BB4,
    tableOrderCount = 4,
    tableOrderHash = 0xA8231374,
    slotTableCount = 121,
    slotTableHash = 0x6E6AE6CE,
    assetTotal = 2012,
    tables = {
        palette = { count = 700, hash = 0x64D0E530 },
        outfit = { count = 745, hash = 0xD9A2B5E1 },
        appearance = { count = 503, hash = 0x5EEED631 },
        meta = { count = 64, hash = 0x2FC0F59F },
    },
}

local function frozen_fnv1a32(value)
    local hash = 0x811C9DC5

    for index = 1, #value do
        hash = ((hash ~ value:byte(index)) * 0x01000193) & 0xFFFFFFFF
    end

    return hash
end

local function frozen_hash_list(values)
    return frozen_fnv1a32(table.concat(values, "\0"))
end

local function frozen_hash_map(values)
    local keys = {}

    for key in pairs(values) do
        keys[#keys + 1] = key
    end

    table.sort(keys)

    local parts = {}

    for _, key in ipairs(keys) do
        parts[#parts + 1] = key .. "=" .. tostring(values[key])
    end

    return frozen_fnv1a32(table.concat(parts, "\0")), #keys
end

local function frozen_fail(message)
    error("ZC1 frozen codebook invariant failed: " .. tostring(message), 2)
end

function M.verify_frozen()
    local manifest = M.FROZEN_MANIFEST

    if M.FROZEN ~= true then
        frozen_fail("FROZEN flag was changed")
    end

    if M.REVISION ~= manifest.revision then
        frozen_fail(
            string.format(
                "revision changed (%s != %s)",
                tostring(M.REVISION),
                tostring(manifest.revision)
            )
        )
    end

    if #M.TAGS ~= manifest.tagCount
        or frozen_hash_list(M.TAGS) ~= manifest.tagHash then
        frozen_fail("tag dictionary changed")
    end

    if #M.TABLE_ORDER ~= manifest.tableOrderCount
        or frozen_hash_list(M.TABLE_ORDER) ~= manifest.tableOrderHash then
        frozen_fail("asset table order changed")
    end

    local slot_hash, slot_count = frozen_hash_map(M.SLOT_TABLE)

    if slot_count ~= manifest.slotTableCount
        or slot_hash ~= manifest.slotTableHash then
        frozen_fail("slot-to-table mapping changed")
    end

    local total = 0
    local seen_assets = {}

    for _, table_name in ipairs(M.TABLE_ORDER) do
        local expected = manifest.tables[table_name]
        local values = M.TABLES[table_name]

        if expected == nil or values == nil then
            frozen_fail("asset table set changed: " .. tostring(table_name))
        end

        if #values ~= expected.count
            or frozen_hash_list(values) ~= expected.hash then
            frozen_fail("asset table changed: " .. tostring(table_name))
        end

        total = total + #values

        for _, asset in ipairs(values) do
            local prior = seen_assets[asset]

            if prior ~= nil then
                frozen_fail(
                    string.format(
                        "asset appears in both %s and %s: %s",
                        tostring(prior),
                        tostring(table_name),
                        tostring(asset)
                    )
                )
            end

            seen_assets[asset] = table_name
        end
    end

    if total ~= manifest.assetTotal then
        frozen_fail(
            string.format(
                "asset total changed (%d != %d)",
                total,
                manifest.assetTotal
            )
        )
    end

    for _, tag in ipairs(M.TAGS) do
        local table_name = M.SLOT_TABLE[tag]

        if manifest.tables[table_name] == nil then
            frozen_fail(
                string.format(
                    "tag %s maps to unknown table %s",
                    tostring(tag),
                    tostring(table_name)
                )
            )
        end
    end

    return true
end

M.verify_frozen()

return M
